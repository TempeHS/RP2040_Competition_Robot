class VL53L0X:
    def __init__(self, i2c, address=0x29):
        self.i2c = i2c
        self.address = address
        if self._r(0xC0) != 0xEE:
            raise OSError("VL53L0X not found")

        self._w(0x89, self._r(0x89) | 0x01)  # 2.8 V I/O
        self._w(0x88, 0x00)
        self._w(0x80, 0x01)
        self._w(0xFF, 0x01)
        self._w(0x00, 0x00)
        self._stop = self._r(0x91)
        self._w(0x00, 0x01)
        self._w(0xFF, 0x00)
        self._w(0x80, 0x00)
        self._w(0x60, self._r(0x60) | 0x12)
        self.i2c.writeto_mem(address, 0x44, bytes([0, 32]))  # 0.25 MCPS rate limit
        self._w(0x01, 0xFF)

        count, aperture = self._spad_info()
        spads = bytearray(self.i2c.readfrom_mem(address, 0xB0, 6))
        self._w(0xFF, 0x01)
        self._w(0x4F, 0x00)
        self._w(0x4E, 0x2C)
        self._w(0xFF, 0x00)
        self._w(0xB6, 0xB4)
        first = 12 if aperture else 0
        enabled = 0
        for i in range(48):
            bit = 1 << (i % 8)
            if i < first or enabled == count:
                spads[i // 8] &= ~bit
            elif spads[i // 8] & bit:
                enabled += 1
        self.i2c.writeto_mem(address, 0xB0, spads)

        for reg, value in _TUNING:
            self._w(reg, value)

        self._w(0x0A, 0x04)  # interrupt on new sample
        self._w(0x84, self._r(0x84) & ~0x10)
        self._w(0x0B, 0x01)

        self._w(0x01, 0x01)
        self._calibrate(0x40)
        self._w(0x01, 0x02)
        self._calibrate(0x00)
        self._w(0x01, 0xE8)

        # Start continuous back-to-back ranging.
        self._w(0x80, 0x01)
        self._w(0xFF, 0x01)
        self._w(0x00, 0x00)
        self._w(0x91, self._stop)
        self._w(0x00, 0x01)
        self._w(0xFF, 0x00)
        self._w(0x80, 0x00)
        self._w(0x00, 0x02)

    def _r(self, reg):
        return self.i2c.readfrom_mem(self.address, reg, 1)[0]

    def _w(self, reg, value):
        self.i2c.writeto_mem(self.address, reg, bytes([value & 0xFF]))

    def _wait_ready(self):
        for _ in range(100):
            if self._r(0x13) & 0x07:
                return
            sleep_ms(1)
        raise OSError("VL53L0X timeout")

    def _spad_info(self):
        self._w(0x80, 0x01)
        self._w(0xFF, 0x01)
        self._w(0x00, 0x00)
        self._w(0xFF, 0x06)
        self._w(0x83, self._r(0x83) | 0x04)
        self._w(0xFF, 0x07)
        self._w(0x81, 0x01)
        self._w(0x80, 0x01)
        self._w(0x94, 0x6B)
        self._w(0x83, 0x00)
        for _ in range(100):
            if self._r(0x83):
                break
            sleep_ms(1)
        else:
            raise OSError("VL53L0X SPAD timeout")
        self._w(0x83, 0x01)
        info = self._r(0x92)
        self._w(0x81, 0x00)
        self._w(0xFF, 0x06)
        self._w(0x83, self._r(0x83) & ~0x04)
        self._w(0xFF, 0x01)
        self._w(0x00, 0x01)
        self._w(0xFF, 0x00)
        self._w(0x80, 0x00)
        return info & 0x7F, info >> 7

    def _calibrate(self, vhv):
        self._w(0x00, 0x01 | vhv)
        self._wait_ready()
        self._w(0x0B, 0x01)
        self._w(0x00, 0x00)

    def read(self):
        """Distance in mm. About 8190 means nothing in range."""
        self._wait_ready()
        d = self.i2c.readfrom_mem(self.address, 0x1E, 2)
        self._w(0x0B, 0x01)
        return d[0] << 8 | d[1]
